// One, few or many: 1 файл, 2 файла, 5 файлов
function plural(n: number, one: string, few: string, many: string) {
  const tens = n % 100, ones = n % 10;
  if (tens >= 11 && tens <= 14) return many;
  return ones === 1 ? one : ones >= 2 && ones <= 4 ? few : many;
}

